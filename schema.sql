-- =====================================================================
--  Student Placement & Career Analytics System
--  schema.sql  -  creates the `placement_analytics` database
--
--  Run in MySQL Workbench (File > Open SQL Script > Execute)
--  or from a terminal:   mysql -u root -p < schema.sql
--
--  WARNING: running this script again DROPS and recreates all tables.
-- =====================================================================

CREATE DATABASE IF NOT EXISTS placement_analytics
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE placement_analytics;

-- Drop views first, then tables (children before parents)
DROP VIEW  IF EXISTS vw_company_skill_demand;
DROP VIEW  IF EXISTS vw_student_skills;
DROP VIEW  IF EXISTS vw_student_placements;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS department_eligibility;
DROP TABLE IF EXISTS company_requirements;
DROP TABLE IF EXISTS student_skills;
DROP TABLE IF EXISTS skills;
DROP TABLE IF EXISTS placements;
DROP TABLE IF EXISTS companies;
DROP TABLE IF EXISTS students;
DROP TABLE IF EXISTS departments;

-- ---------------------------------------------------------------------
-- 0. departments  (makes department names configurable)
-- ---------------------------------------------------------------------
CREATE TABLE departments (
    dept_code   VARCHAR(10)  NOT NULL,
    dept_name   VARCHAR(100) NOT NULL,
    is_active   TINYINT(1)   NOT NULL DEFAULT 1,
    PRIMARY KEY (dept_code),
    UNIQUE KEY uq_dept_name (dept_name)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 1. students
-- ---------------------------------------------------------------------
CREATE TABLE students (
    student_id    VARCHAR(12)   NOT NULL,
    student_name  VARCHAR(100)  NOT NULL,
    department    VARCHAR(10)   NOT NULL,
    batch_year    SMALLINT      NOT NULL,
    cgpa          DECIMAL(4,2)  NOT NULL,
    email         VARCHAR(120)  NOT NULL,
    is_sample     TINYINT(1)    NOT NULL DEFAULT 0,   -- 1 = generated by seed_data.py
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (student_id),
    UNIQUE KEY uq_student_email (email),
    KEY idx_students_batch_dept (batch_year, department),
    KEY idx_students_name (student_name),
    CONSTRAINT fk_students_department FOREIGN KEY (department)
        REFERENCES departments (dept_code) ON UPDATE CASCADE,
    CONSTRAINT chk_students_cgpa  CHECK (cgpa BETWEEN 0 AND 10),
    CONSTRAINT chk_students_batch CHECK (batch_year BETWEEN 2000 AND 2100)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 2. companies
-- ---------------------------------------------------------------------
CREATE TABLE companies (
    company_id        INT          NOT NULL AUTO_INCREMENT,
    company_name      VARCHAR(100) NOT NULL,
    industry          VARCHAR(60)  NOT NULL,
    company_category  VARCHAR(30)  NOT NULL,
    is_sample         TINYINT(1)   NOT NULL DEFAULT 0,
    PRIMARY KEY (company_id),
    UNIQUE KEY uq_company_name (company_name),
    KEY idx_company_category (company_category),
    CONSTRAINT chk_company_category CHECK (company_category IN
        ('Product-Based', 'Service-Based', 'Consulting', 'Core Engineering'))
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 3. placements  (one final offer per student -> UNIQUE student_id)
-- ---------------------------------------------------------------------
CREATE TABLE placements (
    placement_id      INT           NOT NULL AUTO_INCREMENT,
    student_id        VARCHAR(12)   NOT NULL,
    company_id        INT           NOT NULL,
    package_lpa       DECIMAL(6,2)  NOT NULL,
    placement_date    DATE          NOT NULL,
    placement_status  VARCHAR(20)   NOT NULL DEFAULT 'Placed',
    PRIMARY KEY (placement_id),
    UNIQUE KEY uq_placement_student (student_id),
    KEY idx_placements_company (company_id),
    KEY idx_placements_date (placement_date),
    CONSTRAINT fk_placements_student FOREIGN KEY (student_id)
        REFERENCES students (student_id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_placements_company FOREIGN KEY (company_id)
        REFERENCES companies (company_id) ON DELETE RESTRICT,
    CONSTRAINT chk_placements_package CHECK (package_lpa > 0 AND package_lpa <= 200),
    CONSTRAINT chk_placements_status  CHECK (placement_status IN ('Placed', 'Offer Pending'))
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 4. skills  (technical skills AND certifications)
-- ---------------------------------------------------------------------
CREATE TABLE skills (
    skill_id    INT         NOT NULL AUTO_INCREMENT,
    skill_name  VARCHAR(60) NOT NULL,
    skill_type  VARCHAR(20) NOT NULL DEFAULT 'Technical',
    PRIMARY KEY (skill_id),
    UNIQUE KEY uq_skill_name (skill_name),
    CONSTRAINT chk_skill_type CHECK (skill_type IN ('Technical', 'Certification'))
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 5. student_skills  (many-to-many: students <-> skills)
-- ---------------------------------------------------------------------
CREATE TABLE student_skills (
    student_id  VARCHAR(12) NOT NULL,
    skill_id    INT         NOT NULL,
    PRIMARY KEY (student_id, skill_id),          -- prevents duplicate rows
    KEY idx_student_skills_skill (skill_id),
    CONSTRAINT fk_ss_student FOREIGN KEY (student_id)
        REFERENCES students (student_id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_ss_skill FOREIGN KEY (skill_id)
        REFERENCES skills (skill_id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 6. company_requirements  (skills a company asked for in a batch)
-- ---------------------------------------------------------------------
CREATE TABLE company_requirements (
    requirement_id  INT      NOT NULL AUTO_INCREMENT,
    company_id      INT      NOT NULL,
    skill_id        INT      NOT NULL,
    batch_year      SMALLINT NOT NULL,
    PRIMARY KEY (requirement_id),
    UNIQUE KEY uq_requirement (company_id, skill_id, batch_year),
    KEY idx_requirements_batch (batch_year),
    CONSTRAINT fk_cr_company FOREIGN KEY (company_id)
        REFERENCES companies (company_id) ON DELETE CASCADE,
    CONSTRAINT fk_cr_skill FOREIGN KEY (skill_id)
        REFERENCES skills (skill_id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 7. department_eligibility  (is the student allowed to sit for placements?)
-- ---------------------------------------------------------------------
CREATE TABLE department_eligibility (
    student_id              VARCHAR(12) NOT NULL,
    eligible_for_placement  TINYINT(1)  NOT NULL DEFAULT 1,
    batch_year              SMALLINT    NOT NULL,
    PRIMARY KEY (student_id),
    KEY idx_eligibility_batch (batch_year),
    CONSTRAINT fk_elig_student FOREIGN KEY (student_id)
        REFERENCES students (student_id) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- 8. users  (login accounts - passwords are stored as hashes only)
-- ---------------------------------------------------------------------
CREATE TABLE users (
    user_id        INT          NOT NULL AUTO_INCREMENT,
    username       VARCHAR(50)  NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    role           VARCHAR(10)  NOT NULL DEFAULT 'viewer',
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id),
    UNIQUE KEY uq_username (username),
    CONSTRAINT chk_user_role CHECK (role IN ('admin', 'viewer'))
) ENGINE=InnoDB;

-- =====================================================================
--  SHARED DATA DEFINITIONS
--  These views are used by BOTH the Flask app and Tableau, so a
--  "placement", a "CTC band" and an "eligible student" mean exactly
--  the same thing everywhere.
-- =====================================================================

-- One row per student, with placement details (NULL if not placed)
CREATE VIEW vw_student_placements AS
SELECT
    s.student_id,
    s.student_name,
    s.department,
    d.dept_name,
    s.batch_year,
    s.cgpa,
    s.email,
    s.is_sample,
    COALESCE(e.eligible_for_placement, 1)                     AS is_eligible,
    p.placement_id,
    p.placement_status,
    p.package_lpa,
    p.placement_date,
    c.company_id,
    c.company_name,
    c.industry,
    c.company_category,
    CASE WHEN p.placement_status = 'Placed' THEN 1 ELSE 0 END AS is_placed,
    CASE
        WHEN p.placement_status <> 'Placed' OR p.placement_status IS NULL THEN NULL
        WHEN p.package_lpa < 10 THEN '0-10 LPA'
        WHEN p.package_lpa < 20 THEN '10-20 LPA'
        WHEN p.package_lpa < 30 THEN '20-30 LPA'
        ELSE '30+ LPA'
    END                                                       AS ctc_band,
    CASE
        WHEN p.placement_status = 'Placed'        THEN 'Placed'
        WHEN p.placement_status = 'Offer Pending' THEN 'Offer Pending'
        WHEN COALESCE(e.eligible_for_placement, 1) = 0 THEN 'Not Eligible'
        ELSE 'Not Placed'
    END                                                       AS student_status
FROM students s
JOIN departments d                 ON d.dept_code  = s.department
LEFT JOIN department_eligibility e ON e.student_id = s.student_id
LEFT JOIN placements p             ON p.student_id = s.student_id
LEFT JOIN companies c              ON c.company_id = p.company_id;

-- One row per (student, skill)
CREATE VIEW vw_student_skills AS
SELECT
    v.student_id,
    v.department,
    v.batch_year,
    v.is_eligible,
    v.is_placed,
    v.package_lpa,
    sk.skill_id,
    sk.skill_name,
    sk.skill_type
FROM vw_student_placements v
JOIN student_skills ss ON ss.student_id = v.student_id
JOIN skills sk         ON sk.skill_id   = ss.skill_id;

-- One row per (company, required skill, batch)
CREATE VIEW vw_company_skill_demand AS
SELECT
    c.company_id,
    c.company_name,
    c.company_category,
    cr.batch_year,
    sk.skill_name,
    sk.skill_type
FROM company_requirements cr
JOIN companies c ON c.company_id = cr.company_id
JOIN skills sk   ON sk.skill_id  = cr.skill_id;
